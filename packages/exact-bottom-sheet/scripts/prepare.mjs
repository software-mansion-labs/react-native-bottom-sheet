// Generates the two files of @swmansion/exact-bottom-sheet that point back
// into the React Native library, so its native code is reused in place rather
// than copied:
//
// - `apple/exact.json`, the Apple implementation manifest. Exact resolves
//   `sources.swift` relative to the implementation's directory *as installed*
//   (under the app's `node_modules`, where Bun links each file on its own), so
//   a relative path back into `ios/` cannot work there. The manifest lists
//   absolute paths instead: the adapter, and every `ios/HostingView/*.swift`.
// - `web/generated/sheet-controller.js`, `src/web/controller.ts` and what it
//   imports, bundled to one ES module. Exact bundles a web implementation's
//   JavaScript as page code only inside the implementation's own directory,
//   and `src/web/detents.ts` and the adapter take constants and the props
//   validation (`normalizeDetents`, `validateIndex`, `validateSettleDuration`)
//   from `src/bottomSheetUtils.ts`, which imports `react-native` for code they
//   don't use; the bundle resolves `react-native` to an inert stub, and the
//   unused code that would reach it is tree-shaken out.
//
// Usage: bun packages/exact/scripts/prepare.mjs
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

export const packageDir = resolve(import.meta.dir, '..');
export const repoRoot = resolve(packageDir, '../..');

export function writeAppleManifest() {
  const hosting = resolve(repoRoot, 'ios/HostingView');
  const shared = readdirSync(hosting)
    .filter((file) => file.endsWith('.swift'))
    .sort()
    .map((file) => join(hosting, file));
  const manifest = {
    kind: 'implementation',
    implements: '@swmansion/exact-bottom-sheet@^0.1',
    platform: 'apple',
    targets: ['ios'],
    shapes: {},
    options: {},
    names: [],
    views: ['swm-bottom-sheet'],
    hatches: [],
    sources: {
      swift: [resolve(packageDir, 'apple/ExactBottomSheet.swift'), ...shared],
    },
    artifacts: [],
    class: 'ExactBottomSheetModule',
  };
  const out = resolve(packageDir, 'apple/exact.json');
  writeFileSync(out, `${JSON.stringify(manifest, null, 2)}\n`);
  return { out, shared };
}

export async function bundleWebController() {
  const out = resolve(packageDir, 'web/generated/sheet-controller.js');
  mkdirSync(dirname(out), { recursive: true });
  const utils = resolve(repoRoot, 'src/bottomSheetUtils.ts');
  const entry = resolve(dirname(out), 'entry.ts');
  writeFileSync(
    entry,
    `export { BottomSheetWebController } from ${JSON.stringify(resolve(repoRoot, 'src/web/controller.ts'))};\n` +
      `export { CONTENT_HEIGHT_MARKER_NATIVE_ID, isNormalizedDetentClosed, normalizeDetents, validateIndex, validateSettleDuration } from ${JSON.stringify(utils)};\n`
  );
  const result = await Bun.build({
    entrypoints: [entry],
    format: 'esm',
    target: 'browser',
    minify: false,
    define: { __DEV__: 'false' },
    plugins: [
      {
        // `src/bottomSheetUtils.ts` imports `react-native` for the surface
        // style helpers, which neither the controller nor the adapter use.
        name: 'react-native-stub',
        setup(build) {
          build.onResolve({ filter: /^react-native$/ }, () => ({
            path: 'react-native-stub',
            namespace: 'react-native-stub',
          }));
          build.onLoad(
            { filter: /.*/, namespace: 'react-native-stub' },
            () => ({
              contents:
                'export const I18nManager = {}, Platform = {}, StyleSheet = {};\n' +
                'export const processColor = () => null;\n',
              loader: 'js',
            })
          );
        },
      },
    ],
  });
  if (!result.success) {
    throw new Error(
      `bundling src/web failed:\n${result.logs.map(String).join('\n')}`
    );
  }
  const code = await result.outputs[0].text();
  if (
    /from\s*['"]react-native['"]|require\(['"]react-native['"]\)/.test(code)
  ) {
    throw new Error('the web controller bundle still imports react-native');
  }
  if (/processColor|StyleSheet|I18nManager/.test(code)) {
    throw new Error(
      'the web controller bundle reaches the react-native stub: keep the surface style helpers out of it'
    );
  }
  writeFileSync(
    out,
    `// Generated by packages/exact/scripts/prepare.mjs from src/web: do not edit.\n${code}`
  );
  return { out };
}

export async function prepare() {
  const apple = writeAppleManifest();
  const web = await bundleWebController();
  return { apple, web };
}

if (import.meta.main) {
  const { apple, web } = await prepare();
  console.log(`wrote ${apple.out} (${apple.shared.length} shared Swift files)`);
  console.log(`wrote ${web.out}`);
}
